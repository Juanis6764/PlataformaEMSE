INSERT INTO "UsuarioPermiso" ("id_usuario", "id_permiso", "concedido")
SELECT up."id_usuario", pg."id_permiso", up."concedido"
FROM "UsuarioPermiso" up
JOIN "Permiso" pe ON pe."id_permiso" = up."id_permiso"
JOIN equivalencias e ON e.especifico = pe."nombre"
JOIN "Permiso" pg ON pg."nombre" = e.general
ON CONFLICT ("id_usuario", "id_permiso")
DO UPDATE SET "concedido" = EXCLUDED."concedido";

