-- Unifica los permisos específicos creados por intentos anteriores del módulo.
-- Primero conserva todas las asignaciones de rol y usuario en el permiso general
-- equivalente; solo después elimina los permisos redundantes.

WITH equivalencias(especifico, general) AS (
  VALUES
    ('VER_NOTAS_EVALUACIONES', 'VER_NOTAS'),
    ('VER_NOTAS_PROPIAS', 'VER_NOTAS'),
    ('CONFIGURAR_MATERIAS_EVALUACIONES', 'PONDERAR_NOTAS'),
    ('CARGAR_NOTAS_EVALUACIONES', 'REGISTRAR_NOTA'),
    ('ENVIAR_PLANILLA_EVALUACIONES', 'REGISTRAR_NOTA'),
    ('REVISAR_PLANILLAS_EVALUACIONES', 'APROBAR_NOTA'),
    ('REVISAR_NOTAS_SECCION_ACADEMICA', 'APROBAR_NOTA'),
    ('GENERAR_MATRICES_EVALUACIONES', 'GENERAR_MATRIZ'),
    ('PUBLICAR_NOTAS_EVALUACIONES', 'PUBLICAR_NOTA'),
    ('GENERAR_REPORTES_NOTAS', 'GENERAR_CERTIFICADO'),
    ('VER_PREVISUALIZACION_CIERRE_GESTION', 'PUBLICAR_NOTA'),
    ('CERRAR_GESTION_ACADEMICA', 'PUBLICAR_NOTA')
)
INSERT INTO "RolPermiso" ("id_rol", "id_permiso")
SELECT rp."id_rol", pg."id_permiso"
FROM "RolPermiso" rp
JOIN "Permiso" pe ON pe."id_permiso" = rp."id_permiso"
JOIN equivalencias e ON e.especifico = pe."nombre"
JOIN "Permiso" pg ON pg."nombre" = e.general
ON CONFLICT ("id_rol", "id_permiso") DO NOTHING;

